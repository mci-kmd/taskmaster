/**
 * A model family's logo (see `modelFamily`), from svgl (https://svgl.app). Monochrome logos take
 * the current text color, so they follow the theme; the others keep their brand colors. The
 * logos are their owners' trademarks. Raptor is GitHub's model, so it shows Copilot's logo.
 */
export default function ModelFamilyIcon({
  family,
  ...props
}: IconProps & { family: string }): React.JSX.Element {
  switch (family) {
    case 'Claude':
      return <ClaudeLogo {...props} />
    case 'GPT':
    case 'OpenAI o-series':
      return <OpenAiLogo {...props} />
    case 'Gemini':
      return <GeminiLogo {...props} />
    case 'Grok':
      return <GrokLogo {...props} />
    case 'Raptor':
      return <CopilotLogo {...props} />
    default:
      return <AgentIcon {...props} />
  }
}

